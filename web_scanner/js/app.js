/**
 * Главная точка входа приложения.
 * Отвечает за координацию, инициализацию и стартовую сборку всех модулей.
 */
document.addEventListener('DOMContentLoaded', () => {
  // 1. Инициализируем систему авторизации (проверяет сессию и рисует оверлей)
  if (window.Auth) {
    Auth.init();
  }

  // 2. Инициализируем базовые элементы интерфейса (динамические списки)
  if (window.UI) {
    UI.init();
    // Первично выводим журнал логов из кэша LocalStorage
    UI.renderLogs();
  }

  // 3. Запускаем сетевой модуль (индикаторы и слушатели онлайна)
  if (window.Network) {
    Network.init();
    // Автоматически пробуем отправить накопленные в офлайне логи при открытии
    Network.sendUnsynced();
  }
});

